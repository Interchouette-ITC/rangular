use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

mod component;
mod config;
mod styles;

pub use config::Config;

use self::component::{Component, compile_template, discover, relative_label};
use self::styles::append as append_styles;

/// Discover and compile a package's rangular templates and styles.
///
/// Reads `CARGO_MANIFEST_DIR` and `OUT_DIR`, writes generated Rust under
/// `OUT_DIR/rangular`, writes CSS to the configured output path, and emits Cargo
/// rerun directives for the component directory and optional global stylesheet.
/// Panics with the offending path and compiler diagnostics on failure, as
/// expected for a Cargo build script.
pub fn build(config: Config) {
    if let Err(error) = run(config) {
        panic!("rangular build failed: {error}");
    }
}

pub(crate) fn run(config: Config) -> Result<(), String> {
    let manifest = env::var_os("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .ok_or_else(|| "CARGO_MANIFEST_DIR is not set".to_owned())?;
    let out_dir = env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .ok_or_else(|| "OUT_DIR is not set".to_owned())?;
    run_at(config, &manifest, &out_dir)
}

fn run_at(
    config: Config,
    manifest: &std::path::Path,
    out_dir: &std::path::Path,
) -> Result<(), String> {
    let components_dir = manifest.join(&config.components_dir);
    let generated_dir = out_dir.join("rangular");

    println!("cargo:rerun-if-changed={}", components_dir.display());
    if let Some(global_scss) = &config.global_scss {
        println!(
            "cargo:rerun-if-changed={}",
            manifest.join(global_scss).display()
        );
    }

    let components = discover(&components_dir)?;
    fs::create_dir_all(&generated_dir)
        .map_err(|error| format!("create {}: {error}", generated_dir.display()))?;

    let mut css = String::from("/* Generated by rangular from component SCSS. */\n");
    if let Some(global_scss) = &config.global_scss {
        append_styles(
            &manifest.join(global_scss),
            global_scss.display().to_string(),
            &mut css,
        )?;
    }

    let generated = compile_components(&components, manifest, &mut css)?;
    for (view_name, code) in generated {
        let output = generated_dir.join(format!("{view_name}.rs"));
        fs::write(&output, code).map_err(|error| format!("write {}: {error}", output.display()))?;
    }

    let css_output = manifest.join(&config.css_output);
    if let Some(parent) = css_output.parent() {
        fs::create_dir_all(parent)
            .map_err(|error| format!("create {}: {error}", parent.display()))?;
    }
    fs::write(&css_output, css).map_err(|error| format!("write {}: {error}", css_output.display()))
}

fn compile_components(
    components: &[Component],
    manifest: &std::path::Path,
    css: &mut String,
) -> Result<Vec<(String, String)>, String> {
    components
        .iter()
        .map(|component| {
            let (view_name, code) = compile_template(component, manifest)?;
            if let Some(scss_path) = component.scss_path() {
                let label = relative_label(manifest, &scss_path);
                let _ = writeln!(css, "\n/* {} */", component.name);
                append_styles(&scss_path, label, css)?;
            }
            Ok((view_name, code))
        })
        .collect()
}

